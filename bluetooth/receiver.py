# ── Default Configuration ─────────────────────────────────────────
FASTAPI_HOST = os.getenv("FASTAPI_HOST", "127.0.0.1")
FASTAPI_PORT = os.getenv("FASTAPI_PORT", "8000")
FASTAPI_URL = os.getenv("VITE_API_URL", f"http://{FASTAPI_HOST}:{FASTAPI_PORT}")

SENSOR_ENDPOINT = f"{FASTAPI_URL}/sensor"
PREDICT_RF_ENDPOINT = f"{FASTAPI_URL}/predict/rf"
DISCONNECT_ENDPOINT = f"{FASTAPI_URL}/sensor/disconnect"
LED_ACK_ENDPOINT = f"{FASTAPI_URL}/sensor/led-ack"

DEFAULT_COM_PORT = os.getenv("ESP32_COM_PORT", "COM9")
DEFAULT_BAUD_RATE = int(os.getenv("ESP32_BAUD_RATE", 115200))

# Station location coordinates for Random Forest model evaluation
DEFAULT_LATITUDE = float(os.getenv("STATION_LATITUDE", 10.940896))
DEFAULT_LONGITUDE = float(os.getenv("STATION_LONGITUDE", 77.077726))
DEFAULT_ELEVATION = float(os.getenv("STATION_ELEVATION", 318.3))

RECONNECT_DELAY = 5       # Seconds to wait before reconnecting
READ_TIMEOUT = 10         # Serial read timeout in seconds


def log(msg: str):
    """Formatted timestamped console logger."""
    ts = datetime.now().strftime("%H:%M:%S")
    print(f"[{ts}] {msg}", flush=True)


def send_esp32_command(ser: serial.Serial, cmd: str) -> bool:
    """
    Sends a newline-terminated command ('LED_ON' or 'LED_OFF') to the ESP32
    over the single active Bluetooth serial connection.
    Flushes the serial buffer immediately to ensure zero transmission lag.
    """
    if not ser or not ser.is_open:
        return False
    try:
        command_bytes = f"{cmd.strip()}\n".encode("utf-8")
        ser.write(command_bytes)
        ser.flush()
        return True
    except Exception as exc:
        log(f"ERROR sending Bluetooth command '{cmd}' to ESP32: {exc}")
        return False


def post_hardware_ack(command: str, actual_state: str, gpio: int = 23, success: bool = True) -> bool:
    """
    Notifies FastAPI ONLY when an actual hardware acknowledgment has been received
    from the physical ESP32.
    """
    try:
        res = requests.post(
            LED_ACK_ENDPOINT,
            json={
                "command": command,
                "actual_state": actual_state,
                "gpio": gpio,
                "success": success,
            },
            timeout=2,
        )
        return res.status_code == 200
    except Exception as exc:
        log(f"Warning: Failed to record hardware ACK with FastAPI: {exc}")
        return False


def post_led_ack(cmd: str, success: bool = True) -> bool:
    """Backwards-compatible helper."""
    actual_state = "ON" if cmd.strip().upper() == "LED_ON" else "OFF"
    return post_hardware_ack(command=cmd, actual_state=actual_state, gpio=23, success=success)


def post_sensor_data(data: dict) -> dict | None:
    """
    Send parsed physical sensor readings to FastAPI /sensor endpoint.
    Returns response JSON containing current target_led and led_status, or None.
    """
    payload = {
        "temperature": float(data["temperature"]),
        "humidity": float(data["humidity"]),
        "rainfall": float(data["rainfall"]),
        "water_level": float(data["water_level"]),
    }
    if "led" in data and data["led"] is not None:
        payload["led"] = int(data["led"])

    try:
        response = requests.post(
            SENSOR_ENDPOINT,
            json=payload,
            timeout=3,
        )
        if response.status_code == 200:
            return response.json()
        else:
            log(f"[Sensor API] FastAPI returned error {response.status_code}: {response.text}")
            return None
    except requests.exceptions.ConnectionError:
        log("ERROR: Cannot reach FastAPI at http://127.0.0.1:8000")
        log("       Make sure FastAPI is running: python -m uvicorn backend.main:app --host 127.0.0.1 --port 8000")
        return None
    except Exception as e:
        log(f"ERROR posting to FastAPI /sensor: {e}")
        return None


def query_rf_prediction(
    sensor_data: dict,
    latitude: float,
    longitude: float,
    elevation: float,
) -> dict | None:
    """
    Requests a real-time prediction from the active Random Forest model
    via the existing FastAPI POST /predict/rf endpoint.

    Input features (7 required):
      - latitude, longitude, elevation (from station config)
      - rainfall, temperature, humidity, water_level (from live ESP32)

    Returns:
        {
            "prediction": 0 | 1,
            "status": "NO FLOOD" | "HIGH FLOOD ALERT",
            "message": str,
            "id": int,
            "timestamp": str,
            "execution_time_ms": float
        }
        or None on failure.
    """
    payload = {
        "latitude": float(latitude),
        "longitude": float(longitude),
        "elevation": float(elevation),
        "rainfall": float(sensor_data["rainfall"]),
        "temperature": float(sensor_data["temperature"]),
        "humidity": float(sensor_data["humidity"]),
        "water_level": float(sensor_data["water_level"]),
    }
    try:
        response = requests.post(
            PREDICT_RF_ENDPOINT,
            json=payload,
            timeout=3,
        )
        if response.status_code == 200:
            return response.json()
        else:
            log(f"[Prediction RF] API returned HTTP {response.status_code}: {response.text}")
            return None
    except requests.exceptions.ConnectionError:
        log("[Prediction RF] ERROR: Cannot connect to /predict/rf. Ensure FastAPI is running.")
        return None
    except requests.exceptions.Timeout:
        log("[Prediction RF] ERROR: Request to /predict/rf timed out.")
        return None
    except Exception as exc:
        log(f"[Prediction RF] Unexpected error: {exc}")
        return None


def notify_disconnect():
    """Tell FastAPI the ESP32 has disconnected."""
    try:
        requests.post(DISCONNECT_ENDPOINT, timeout=2)
    except Exception:
        pass


def parse_esp32_message(line: str) -> dict | None:
    """
    Parses a single line from the ESP32 Bluetooth serial stream.
    Supports:
      1. Hardware ACK JSON: {"ack": "LED_ON"|"LED_OFF", "gpio": 23, "state": 0|1}
      2. Telemetry JSON: {"temperature": 34.2, "humidity": 56.1, "rainfall": 0.0, "water_level": 0.0, "led": 0|1}
      3. Legacy comma-separated sensor stream
    """
    line = line.strip()
    if not line:
        return None

    try:
        data = json.loads(line)

        # 1. Hardware ACK packet
        if "ack" in data:
            cmd = str(data["ack"]).strip().upper()
            state_val = data.get("state")
            actual_state = "ON" if (state_val == 1 or cmd == "LED_ON") else "OFF"
            gpio = int(data.get("gpio", 23))
            return {
                "type": "ack",
                "command": cmd,
                "state": actual_state,
                "gpio": gpio,
            }

        # 2. Sensor telemetry packet
        required = ["temperature", "humidity", "rainfall", "water_level"]
        if all(k in data for k in required):
            payload = {
                "type": "sensor",
                "temperature": float(data["temperature"]),
                "humidity": float(data["humidity"]),
                "rainfall": float(data["rainfall"]),
                "water_level": float(data["water_level"]),
            }
            if "led" in data and data["led"] is not None:
                payload["led"] = int(data["led"])
                payload["hardware_led"] = "ON" if data["led"] == 1 else "OFF"
            return payload

        log(f"WARNING: Incomplete JSON received: {line}")
        return None
    except json.JSONDecodeError:
        # Fallback for comma-separated legacy stream: "28.5,75.0,12.0,1.8"
        parts = line.split(",")
        if len(parts) == 4:
            try:
                return {
                    "type": "sensor",
                    "temperature": float(parts[0]),
                    "humidity": float(parts[1]),
                    "rainfall": float(parts[2]),
                    "water_level": float(parts[3]),
                }
            except ValueError:
                pass
        log(f"WARNING: Could not parse serial line: {line!r}")
        return None


def parse_sensor_line(line: str) -> dict | None:
    """Helper for sensor data backwards compatibility."""
    msg = parse_esp32_message(line)
    if msg and msg.get("type") == "sensor":
        ret = {
            "temperature": msg["temperature"],
            "humidity": msg["humidity"],
            "rainfall": msg["rainfall"],
            "water_level": msg["water_level"],
        }
        if "led" in msg:
            ret["led"] = msg["led"]
            ret["hardware_led"] = msg["hardware_led"]
        return ret
    return None


def run_receiver(
    port: str,
    baud_rate: int = DEFAULT_BAUD_RATE,
    latitude: float = DEFAULT_LATITUDE,
    longitude: float = DEFAULT_LONGITUDE,
    elevation: float = DEFAULT_ELEVATION,
):
    """
    Main loop:
      1. Opens a single Bluetooth Serial connection to the ESP32.
      2. Initializes physical LED to OFF state.
      3. Reads telemetry JSON lines.
      4. Forwards telemetry to FastAPI /sensor.
      5. Runs Random Forest prediction on laptop via /predict/rf.
      6. Transmits LED_ON or LED_OFF back to ESP32 over the same connection.
      7. Applies safe fallbacks on API failure or serial disconnection.
    """
    log("==================================================")
    log(" FLOODGUARD BLUETOOTH RECEIVER & LED CONTROLLER")
    log("==================================================")
    log(f"Target Port : {port}")
    log(f"Baud Rate   : {baud_rate}")
    log(f"FastAPI URL : {FASTAPI_URL}")
    log(f"Station Site: Lat={latitude:.6f}, Lon={longitude:.6f}, Elev={elevation:.1f}m")
    log("-" * 50)

    while True:
        ser = None
        current_led_state = None  # None = uninitialized, True = ON, False = OFF

        try:
            log(f"Opening Bluetooth Serial on {port}...")
            # Single serial connection for bidirectional communication
            ser = serial.Serial(port, baud_rate, timeout=READ_TIMEOUT)
            log(f"Connected to {port}! Bidirectional link established.")

            # Reconnect & Synchronize:
            # Query FastAPI to get current active desired LED prediction state
            target_cmd = "LED_OFF"
            try:
                status_res = requests.get(f"{FASTAPI_URL}/sensor/led-status", timeout=2)
                if status_res.status_code == 200:
                    target_cmd = status_res.json().get("target_command", "LED_OFF")
            except Exception:
                pass

            log(f"[LED] Reconnected to ESP32. Synchronizing physical LED to active prediction: {target_cmd}")
            send_esp32_command(ser, target_cmd)
            # Hardware state starts as UNKNOWN until verified hardware ACK arrives from ESP32
            current_led_state = None
            log("Press Ctrl+C to stop.")
            log("-" * 50)

            consecutive_sensor_errors = 0
            consecutive_pred_errors = 0

            while True:
                try:
                    raw = ser.readline()
                    if not raw:
                        # Timeout with no data received
                        log("WARNING: Serial read timeout (no data from ESP32). Checking connection...")
                        if current_led_state is True:
                            # Safe fallback: turn LED OFF if telemetry drops
                            log("[LED] [SAFE FALLBACK] Telemetry timed out. Turning LED OFF.")
                            send_esp32_command(ser, "LED_OFF")
                            current_led_state = False
                        break

                    line = raw.decode("utf-8", errors="ignore")
                    msg = parse_esp32_message(line)

                    if not msg:
                        continue

                    # CASE 1: Incoming Hardware Acknowledgment from ESP32
                    if msg.get("type") == "ack":
                        cmd = msg["command"]
                        actual_state = msg["state"]
                        gpio = msg.get("gpio", 23)
                        current_led_state = (actual_state == "ON")
                        post_hardware_ack(command=cmd, actual_state=actual_state, gpio=gpio, success=True)
                        log(f"[ESP32 ACK] Physical GPIO {gpio} confirmed {actual_state} for command '{cmd}' ✓")
                        continue

                    # CASE 2: Incoming Sensor Telemetry from ESP32
                    if msg.get("type") == "sensor":
                        # If packet includes verified hardware pin state, update FastAPI confirmation
                        if "hardware_led" in msg:
                            current_led_state = (msg["hardware_led"] == "ON")
                            post_hardware_ack(
                                command="LED_ON" if current_led_state else "LED_OFF",
                                actual_state=msg["hardware_led"],
                                gpio=23,
                                success=True,
                            )

                        # Step 1: Forward live telemetry to FastAPI /sensor
                        sensor_res = post_sensor_data(msg)
                        backend_target_led = None
                        backend_synced = True
                        if sensor_res:
                            consecutive_sensor_errors = 0
                            backend_target_led = sensor_res.get("target_led")
                            backend_synced = sensor_res.get("led_status", {}).get("synced", True)
                        else:
                            consecutive_sensor_errors += 1
                            if consecutive_sensor_errors >= 5:
                                log("WARNING: Repeated FastAPI /sensor posting errors.")

                        # Step 2: Synchronize with target prediction command from FastAPI
                        if backend_target_led:
                            target_is_on = (backend_target_led == "LED_ON")
                            # If hardware is unsynced or current state differs from desired target
                            if not backend_synced or current_led_state != target_is_on:
                                log(f"[LED COMMAND] Target is {backend_target_led} (Physical is {current_led_state}). Transmitting to ESP32 on {port}...")
                                send_esp32_command(ser, backend_target_led)
                                # Truthful reporting: do not post fake ACK here; wait for ESP32's ACK response!

                except serial.SerialException as se:
                    log(f"Serial communication error: {se}")
                    break
                except UnicodeDecodeError:
                    log("WARNING: Byte decoding error from ESP32 stream (check baud rate).")
                    continue

        except serial.SerialException as e:
            log(f"Cannot open port {port}: {e}")
            log("Troubleshooting checklist:")
            log("  1. Ensure ESP32 is powered on and paired in Windows Bluetooth settings.")
            log(f"  2. Verify COM port {port} in Device Manager → Ports (COM & LPT).")
            log(f"  3. Ensure no other application (e.g. Arduino Serial Monitor) is using {port}.")
        except KeyboardInterrupt:
            log("\nReceiver stopped by user (Ctrl+C).")
            if ser and ser.is_open:
                log("[LED] Shutting down: turning physical LED OFF.")
                send_esp32_command(ser, "LED_OFF")
                ser.close()
            notify_disconnect()
            sys.exit(0)
        finally:
            notify_disconnect()
            if ser and ser.is_open:
                try:
                    send_esp32_command(ser, "LED_OFF")
                    ser.close()
                except Exception:
                    pass

        log(f"Reconnecting to {port} in {RECONNECT_DELAY} seconds...")
        try:
            time.sleep(RECONNECT_DELAY)
        except KeyboardInterrupt:
            log("\nReceiver stopped by user.")
            sys.exit(0)


def check_fastapi():
    """Verify FastAPI is reachable before starting Bluetooth receiver."""
    try:
        r = requests.get(FASTAPI_URL, timeout=3)
        log(f"FastAPI is reachable at {FASTAPI_URL} (status: {r.status_code})")
        return True
    except Exception:
        log(f"WARNING: FastAPI is not currently reachable at {FASTAPI_URL}")
        log("         Start FastAPI first: python -m uvicorn backend.main:app --host 127.0.0.1 --port 8000")
        log("         The receiver will attempt to reconnect and query predictions when FastAPI starts.")
        return False


def list_com_ports():
    """List available COM ports to assist in identifying the ESP32."""
    try:
        import serial.tools.list_ports
        ports = list(serial.tools.list_ports.comports())
        if ports:
            log("Available system COM ports:")
            for p in ports:
                log(f"  {p.device:10s} — {p.description}")
        else:
            log("No active COM ports detected. Ensure Bluetooth pairing is complete.")
    except ImportError:
        pass


def main():
    parser = argparse.ArgumentParser(
        description="FloodGuard Bluetooth Receiver & ML LED Controller"
    )
    parser.add_argument(
        "--port", "-p",
        type=str,
        default=DEFAULT_COM_PORT,
        help=f"Bluetooth COM port of the ESP32 (default: {DEFAULT_COM_PORT})",
    )
    parser.add_argument(
        "--baud", "-b",
        type=int,
        default=DEFAULT_BAUD_RATE,
        help=f"Baud rate (default: {DEFAULT_BAUD_RATE})",
    )
    parser.add_argument(
        "--lat",
        type=float,
        default=DEFAULT_LATITUDE,
        help=f"Station Latitude for RF inference (default: {DEFAULT_LATITUDE})",
    )
    parser.add_argument(
        "--lon",
        type=float,
        default=DEFAULT_LONGITUDE,
        help=f"Station Longitude for RF inference (default: {DEFAULT_LONGITUDE})",
    )
    parser.add_argument(
        "--elevation",
        type=float,
        default=DEFAULT_ELEVATION,
        help=f"Station Elevation in meters for RF inference (default: {DEFAULT_ELEVATION})",
    )
    parser.add_argument(
        "--list-ports",
        action="store_true",
        help="List available system COM ports and exit",
    )
    args = parser.parse_args()

    if args.list_ports:
        list_com_ports()
        sys.exit(0)

    port = args.port
    if not port:
        list_com_ports()
        print()
        port = input(f"Enter the COM port for ESP32 (default: {DEFAULT_COM_PORT}): ").strip()
        if not port:
            port = DEFAULT_COM_PORT

    check_fastapi()
    run_receiver(
        port=port,
        baud_rate=args.baud,
        latitude=args.lat,
        longitude=args.lon,
        elevation=args.elevation,
    )


if __name__ == "__main__":
    main()
